def input_filter(text: str):
    for category, patterns in BLOCKLIST.items():
        for p in patterns:
            if p.search(text):
                return {
                    "decision": "block",
                    "layer": "input_filter",
                    "category": category,
                    "confidence": 1.0
                }
    return None


# =========================
# MODERATION PIPELINE
# =========================

class ModerationPipeline:
    def __init__(self, model, tokenizer, calibrator, device=None):
        self.model = model
        self.tokenizer = tokenizer
        self.calibrator = calibrator

        self.device = device or torch.device(
            "cuda" if torch.cuda.is_available() else "cpu"
        )

        self.model.to(self.device)
        self.model.eval()

    def _predict_proba(self, text):
        inputs = self.tokenizer(
            text,
            return_tensors="pt",
            truncation=True,
            padding=True,
            max_length=128
        )

        inputs = {k: v.to(self.device) for k, v in inputs.items()}

        with torch.no_grad():
            outputs = self.model(**inputs)

        raw_prob = torch.softmax(outputs.logits, dim=-1)[0][1].item()

        # Calibration step
        calibrated = self.calibrator.predict_proba([[raw_prob]])[0][1]

        return calibrated

    def predict(self, text: str):

        # Layer 1
        rule_result = input_filter(text)
        if rule_result:
            return rule_result

        # Layer 2
        score = self._predict_proba(text)

        if score >= 0.6:
            return {"decision": "block", "layer": "model", "confidence": score}

        if score <= 0.4:
            return {"decision": "allow", "layer": "model", "confidence": score}

        # Layer 3
        return {"decision": "review", "layer": "model", "confidence": score}